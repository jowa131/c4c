let activeTopicId = null;
let currentDeck = [];
let currentIndex = 0;

const homeMenu = document.getElementById('homeMenu');
const carouselView = document.getElementById('carouselView');
const homeBtn = document.getElementById('homeBtn');
const cardsWrapper = document.getElementById('cardsWrapper');
const prevBtn = document.getElementById('prevBtn');
const nextBtn = document.getElementById('nextBtn');
const progressIndicator = document.getElementById('progressIndicator');

// Initialize Home Menu
function initHomeMenu() {
    homeMenu.innerHTML = '';
    for (const [key, data] of Object.entries(topicsData)) {
        const card = document.createElement('div');
        card.className = 'menu-card';
        card.innerHTML = `
            <div class="menu-icon">${data.icon}</div>
            <div class="menu-title">${data.title}</div>
            <div class="menu-desc">${data.desc}</div>
        `;
        card.addEventListener('click', () => loadTopic(key));
        homeMenu.appendChild(card);
    }
}

function loadTopic(topicId) {
    activeTopicId = topicId;
    currentDeck = topicsData[topicId].cards;
    currentIndex = 0;
    
    // Switch View
    homeMenu.style.display = 'none';
    carouselView.style.display = 'flex';
    homeBtn.style.display = 'block';
    
    // Render Deck
    renderCards();
}

homeBtn.addEventListener('click', () => {
    if ('speechSynthesis' in window) window.speechSynthesis.cancel();
    carouselView.style.display = 'none';
    homeBtn.style.display = 'none';
    homeMenu.style.display = 'grid';
});

// TTS Function Play
let availableVoices = [];
function loadVoices() {
    availableVoices = window.speechSynthesis.getVoices();
}
if ('speechSynthesis' in window) {
    loadVoices();
    if (speechSynthesis.onvoiceschanged !== undefined) {
        speechSynthesis.onvoiceschanged = loadVoices;
    }
}

function playSound(text, lang, btnElement) {
    if ('speechSynthesis' in window) {
        window.speechSynthesis.cancel();
        
        document.querySelectorAll('.sound-btn.playing').forEach(btn => btn.classList.remove('playing'));
        
        const utterance = new SpeechSynthesisUtterance(text);
        utterance.lang = lang;
        utterance.rate = 0.9;
        utterance.pitch = 1.1;

        if (availableVoices.length > 0) {
            let selectedVoice = null;
            if (lang === 'en-GB') {
                let gbVoices = availableVoices.filter(v => v.lang.includes('en-GB') || v.lang.includes('en_GB'));
                if (gbVoices.length === 0) gbVoices = availableVoices.filter(v => v.lang.startsWith('en'));
                
                const premiumKeywords = ['google', 'apple', 'natural', 'premium', 'daniel', 'arthur', 'uk english'];
                selectedVoice = gbVoices.find(v => premiumKeywords.some(k => v.name.toLowerCase().includes(k))) || gbVoices[0];
            } else if (lang === 'ko-KR') {
                let krVoices = availableVoices.filter(v => v.lang.includes('ko-KR') || v.lang.includes('ko_KR'));
                const premiumKrKeywords = ['google', 'apple', 'yuna', 'premium', 'natural'];
                selectedVoice = krVoices.find(v => premiumKrKeywords.some(k => v.name.toLowerCase().includes(k))) || krVoices[0];
            }
            if (selectedVoice) {
                utterance.voice = selectedVoice;
            }
        }
        
        if (btnElement) {
            utterance.onstart = () => btnElement.classList.add('playing');
            utterance.onend = () => btnElement.classList.remove('playing');
            utterance.onerror = () => btnElement.classList.remove('playing');
        }

        window.speechSynthesis.speak(utterance);
    } else {
        alert("이 브라우저에서는 소리 재생을 지원하지 않아요.");
    }
}

window.playSound = playSound;

function renderCards() {
    cardsWrapper.innerHTML = '';
    progressIndicator.innerHTML = '';
    
    currentDeck.forEach((data, index) => {
        const card = document.createElement('div');
        card.className = `card ${index === 0 ? 'active' : ''} ${index < currentIndex ? 'prev' : ''}`;
        card.dataset.index = index;

        const vocabHtml = data.vocab.map(v => `
            <li class="vocab-item">
                <div class="vocab-header">
                    <span class="vocab-word">🧩 ${v.word}</span>
                    <button class="sound-btn" onclick="playSound('${v.word.replace(/'/g, "\\'")}', 'en-GB', this)" title="영어 듣기">
                        🔊
                    </button>
                </div>
                <span class="vocab-meaning">${v.meaning || v.단어}</span>
            </li>
        `).join('');

        card.innerHTML = `
            <div class="card-image-container">
                <img src="${data.image}" alt="Slide image" class="card-image">
            </div>
            <div class="card-content">
                <div class="text-wrapper">
                    <div class="main-text">${data.text}</div>
                    <button class="sound-btn" onclick="playSound('${data.text.replace(/'/g, "\\'")}', 'ko-KR', this)" title="한국어 설명 듣기" style="flex-shrink:0;">
                        🔊
                    </button>
                </div>
                <div class="vocab-section">
                    <div class="vocab-title">🔡 그림 속 영어 뜻 알아보기</div>
                    <ul class="vocab-list">
                        ${vocabHtml}
                    </ul>
                </div>
            </div>
        `;

        cardsWrapper.appendChild(card);

        const dot = document.createElement('div');
        dot.className = `dot ${index === 0 ? 'active' : ''}`;
        dot.addEventListener('click', () => goToCard(index));
        progressIndicator.appendChild(dot);
    });
    
    updateButtons();
}

function updateCards() {
    const cards = document.querySelectorAll('.card');
    const dots = document.querySelectorAll('.dot');
    
    if ('speechSynthesis' in window) window.speechSynthesis.cancel(); 
    
    cards.forEach((card, index) => {
        card.classList.remove('active', 'prev');
        if (index === currentIndex) card.classList.add('active');
        else if (index < currentIndex) card.classList.add('prev');
    });

    dots.forEach((dot, index) => dot.classList.toggle('active', index === currentIndex));
    updateButtons();
}

function updateButtons() {
    prevBtn.style.opacity = currentIndex === 0 ? '0.5' : '1';
    prevBtn.style.cursor = currentIndex === 0 ? 'not-allowed' : 'pointer';
    nextBtn.style.opacity = currentIndex === currentDeck.length - 1 ? '0.5' : '1';
    nextBtn.style.cursor = currentIndex === currentDeck.length - 1 ? 'not-allowed' : 'pointer';
}

function goToCard(index) {
    if (index < 0 || index >= currentDeck.length) return;
    currentIndex = index;
    updateCards();
}

prevBtn.addEventListener('click', () => {
    if (currentIndex > 0) goToCard(currentIndex - 1);
});

nextBtn.addEventListener('click', () => {
    if (currentIndex < currentDeck.length - 1) goToCard(currentIndex + 1);
});

let touchStartX = 0;
let touchStartY = 0;
let touchEndX = 0;
let touchEndY = 0;

cardsWrapper.addEventListener('touchstart', e => {
    touchStartX = e.changedTouches[0].screenX;
    touchStartY = e.changedTouches[0].screenY;
}, {passive: true});

cardsWrapper.addEventListener('touchend', e => {
    touchEndX = e.changedTouches[0].screenX;
    touchEndY = e.changedTouches[0].screenY;
    handleSwipe();
}, {passive: true});

function handleSwipe() {
    const swipeThreshold = 50; 
    const diffX = touchEndX - touchStartX;
    const diffY = touchEndY - touchStartY;
    
    if (Math.abs(diffX) > Math.abs(diffY)) {
        if (diffX < -swipeThreshold) goToCard(currentIndex + 1);
        else if (diffX > swipeThreshold) goToCard(currentIndex - 1);
    }
}

document.addEventListener('keydown', e => {
    if (carouselView.style.display !== 'none') {
        if (e.key === 'ArrowLeft') goToCard(currentIndex - 1);
        if (e.key === 'ArrowRight') goToCard(currentIndex + 1);
    }
});

